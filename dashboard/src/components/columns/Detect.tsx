import { Activity, Mountain, Radiation, Wind, type LucideIcon } from 'lucide-react'
import { focusIncidentId, store, useStore } from '@/lib/store'
import type { IncidentKind } from '@/lib/types'
import { cn } from '@/lib/utils'
import { missionT } from '@/lib/format'
import { Empty, PhaseColumn, Section } from './PhaseColumn'
import { Fig, KindBadge } from '../Kind'
import { Sensors } from '../Sensors'
import { Tooltip, TooltipContent, TooltipTrigger } from '../ui/tooltip'

const ICON: Record<IncidentKind, LucideIcon> = { sep: Radiation, quake: Activity, dust: Wind, science: Mountain }

export function DetectColumn() {
  const order = useStore((s) => s.order)
  const incidents = useStore((s) => s.incidents)
  const focusId = useStore(focusIncidentId)
  const scenario = useStore((s) => s.hello?.scenario)
  const liveId = useStore((s) => s.snapshot?.incident_id ?? null)
  const focus = focusId ? incidents[focusId]?.incident : undefined
  // The readings are generated by the engine for this exercise, so they are never shown as measurements.
  const sensorKind = 'scenario' as const
  const sensorSource = 'Simulated sensor reading produced by the engine for this scenario. Not an instrument observation.'
  const pending = (scenario ?? []).filter((s) => !incidents[s.id])

  return (
    <PhaseColumn phase="detect">
      <Section title="Incident feed" first aside={order.length ? `${order.length} so far` : undefined}>
        {order.length === 0 ? (
          <Empty title="No incident yet">Start the demo or trigger an incident from the top bar. Sensor traces below stay live.</Empty>
        ) : (
          <ul className="-mx-1.5 space-y-px">
            {[...order].reverse().map((id) => {
              const inc = incidents[id].incident
              const Icon = ICON[inc.kind] ?? Activity
              const sel = id === focusId
              return (
                <li key={id} className="anim-rise">
                  <button
                    onClick={() => store.set({ focusId: id === liveId ? null : id, selectedRoute: null })}
                    className={cn('card-hover relative block w-full rounded-[3px] px-2 py-2 text-left', sel && 'bg-panel2')}
                    aria-pressed={sel}
                  >
                    <span className={cn('absolute inset-y-1.5 left-0 w-[2px] rounded-full transition-colors', sel ? 'bg-accent' : 'bg-transparent')} />
                    <div className="flex items-start gap-2">
                      <Icon size={15} className={cn('mt-[1px] shrink-0', sel ? 'text-ink' : 'text-ink3')} strokeWidth={1.7} />
                      <div className="min-w-0 flex-1">
                        <div className="flex items-baseline justify-between gap-2">
                          <span className="text-[13px] font-medium leading-tight text-ink">{inc.title}</span>
                          <span className="num shrink-0 text-[10px] text-ink3">{missionT(inc.t)}</span>
                        </div>
                        {inc.summary && <p className="mt-0.5 text-[12px] leading-snug text-ink2">{inc.summary}</p>}
                        <div className="mt-1.5 flex items-center gap-1.5">
                          <KindBadge kind={inc.scenario ? 'scenario' : 'measured'} label={inc.scenario ? 'Scenario incident' : 'Observation'} source={inc.source} className="shrink-0" />
                          {inc.source && (
                            <Tooltip>
                              <TooltipTrigger asChild><span className="truncate text-[10.5px] text-ink3">{inc.source}</span></TooltipTrigger>
                              <TooltipContent>{inc.source}</TooltipContent>
                            </Tooltip>
                          )}
                        </div>
                      </div>
                    </div>
                  </button>
                </li>
              )
            })}
          </ul>
        )}
        {focus?.params && focus.params.length > 0 && (
          <dl className="mt-3 space-y-1.5 rule-t pt-2.5">
            <div className="eyebrow mb-1">Incident figures</div>
            {focus.params.map((p) => (
              <div key={p.label} className="flex items-baseline justify-between gap-3 text-[12px]">
                <dt className="leading-snug text-ink2">{p.label}</dt>
                <dd><Fig value={p.value} unit={p.unit} kind={p.kind} source={p.source} label={p.label} /></dd>
              </div>
            ))}
          </dl>
        )}
      </Section>

      {pending.length > 0 && (
        <Section title="Still to come" aside="scenario script">
          <ul className="space-y-1">
            {pending.map((p) => (
              <li key={p.id} className="flex items-baseline justify-between gap-2 text-[12px] text-ink3">
                <span>{p.title}</span><span className="num text-[10px]">{missionT(p.at_s)}</span>
              </li>
            ))}
          </ul>
        </Section>
      )}

      <Section title="Live sensors">
        <Sensors kind={sensorKind} kindSource={sensorSource} />
      </Section>
    </PhaseColumn>
  )
}
